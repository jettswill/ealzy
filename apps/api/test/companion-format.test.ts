import { describe, expect, it } from "vitest";
import { formatCompanionAnswer } from "../src/modules/assistant/companion-format.js";

describe("formatCompanionAnswer", () => {
  it("breaks an inline numbered task list onto separate lines", () => {
    const packed =
      "На данный момент у тебя есть следующие просроченные задачи: 1. Составить план обучения продажам. 2. Построить план работ по лоцен. 3. Добавить в интерфейсе количество выполненных дел в конце недели. 4. Репетировать голосовую позицию. Обрати внимание, что у тебя 4 просроченные задачи, и стоит их решить в первую очередь.";
    expect(formatCompanionAnswer(packed)).toBe(
      [
        "На данный момент у тебя есть следующие просроченные задачи:",
        "",
        "1. Составить план обучения продажам.",
        "2. Построить план работ по лоцен.",
        "3. Добавить в интерфейсе количество выполненных дел в конце недели.",
        "4. Репетировать голосовую позицию.",
        "",
        "Обрати внимание, что у тебя 4 просроченные задачи, и стоит их решить в первую очередь.",
      ].join("\n"),
    );
  });

  it("is stable when the list is already wrapped", () => {
    const formatted = formatCompanionAnswer(
      "Просрочено:\n\n1. Созвон.\n2. Отчёт.\n\nСними это первым.",
    );
    expect(formatCompanionAnswer(formatted)).toBe(formatted);
  });

  it("does not reflow search hits with URLs", () => {
    const block = [
      "Вот что нашлось:",
      "• Кофейня — рядом",
      "  https://example.com/place",
    ].join("\n");
    expect(formatCompanionAnswer(block)).toBe(
      ["Вот что нашлось:", "", "• **Кофейня** — рядом", "  https://example.com/place"].join("\n"),
    );
  });

  it("turns bold title-dash lines into a task list", () => {
    const packed = [
      "Доброе утро! Вот ваши задачи на сегодня:",
      "",
      "**Составить план обучения продажам** — срок до 11 сентября.",
      "**Поставить кулер на 108** — срок до 11 сентября.",
      "",
      "Удачного дня!",
    ].join("\n");
    expect(formatCompanionAnswer(packed)).toBe(
      [
        "Доброе утро! Вот ваши задачи на сегодня:",
        "",
        "• **Составить план обучения продажам** — срок до 11 сентября.",
        "• **Поставить кулер на 108** — срок до 11 сентября.",
        "",
        "Удачного дня!",
      ].join("\n"),
    );
  });

  it("splits dense prose into short paragraphs and bolds list titles", () => {
    const packed = [
      "Сейчас выведу 4 просроченные задачи, которые видны в основном списке. Это твои хвосты с прошлой недели — их стоит хотя бы увидеть, чтобы решить: делать или закрывать.",
      "",
      "1. Изучать курсы Вани — ежедневное, цель: на основе ИИ",
      "2. Продумать стратегию продукта по видеоаналитике — запиналить и передать Эльдару",
      "3. Распечатать сертификат для Кати и собрать документы",
      "",
      "Все остальные просроченные задачи уже были в списке. Если появятся новые хвосты — сразу скажу.",
    ].join("\n");
    expect(formatCompanionAnswer(packed)).toBe(
      [
        "Сейчас выведу 4 просроченные задачи, которые видны в основном списке.",
        "",
        "Это твои хвосты с прошлой недели — их стоит хотя бы увидеть, чтобы решить: делать или закрывать.",
        "",
        "1. **Изучать курсы Вани** — ежедневное, цель: на основе ИИ",
        "2. **Продумать стратегию продукта по видеоаналитике** — запиналить и передать Эльдару",
        "3. Распечатать сертификат для Кати и собрать документы",
        "",
        "Все остальные просроченные задачи уже были в списке.",
        "",
        "Если появятся новые хвосты — сразу скажу.",
      ].join("\n"),
    );
  });

  it("numbers consecutive bold-colon steps", () => {
    const packed = [
      "Чтобы начать, можешь попробовать следующие шаги:",
      "",
      "**Определить цель**: что именно ты хочешь достичь.",
      "**Выбрать метод**: медитация или дневник.",
      "**Запланировать время**: выдели слот в расписании.",
    ].join("\n");
    expect(formatCompanionAnswer(packed)).toBe(
      [
        "Чтобы начать, можешь попробовать следующие шаги:",
        "",
        "1. **Определить цель**: что именно ты хочешь достичь.",
        "2. **Выбрать метод**: медитация или дневник.",
        "3. **Запланировать время**: выдели слот в расписании.",
      ].join("\n"),
    );
  });
});
